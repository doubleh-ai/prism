'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const escape = value => String(value).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const app = {};
const context = vm.createContext({App:app,esc:escape,escAttr:escape,document:{addEventListener(){}},ChatRender:{stringify:value=>typeof value==='string'?value:JSON.stringify(value)}});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../static/js/app.research.js'),'utf8'),context);
const claim = {claim_id:'a',kind:'fact',statement:'合成数字',value:'120',unit:'万吨',period:'2025'};
app._researchBundle = {claims:[claim],numerical_checks:{conflicts:[{claim_ids:['a','b']}]}};
assert.match(app._researchClaimsHTML([claim]),/同口径数值有差异/);
assert.doesNotMatch(app._researchClaimsHTML([{...claim,claim_id:'other'}]),/同口径数值有差异/);
app._researchBundle = {};
assert.doesNotMatch(app._researchClaimsHTML([claim]),/同口径数值有差异/);
assert.match(app._researchClaimsHTML([{...claim,statement:'<img src=x onerror=steal()>',value:'<script>steal()</script>'}]),/&lt;img/);
assert.doesNotMatch(app._researchClaimsHTML([{...claim,value:'<script>steal()</script>'}]),/<script>/);
app._researchBundle = {numerical_checks:{conflicts:[null,{claim_ids:'not-an-array'}]}};
assert.doesNotThrow(()=>app._researchClaimsHTML([claim]));
app._researchBundle = {history_checks:{conflicts:[{current_claim_ids:['a'],claim_ids:['a','older']}]}};
assert.match(app._researchClaimsHTML([claim]),/与历史同口径数值有差异/);
assert.doesNotMatch(app._researchClaimsHTML([{...claim,claim_id:'older'}]),/与历史同口径数值有差异/);
app._researchBundle = {history_checks:{conflicts:[null,{current_claim_ids:'not-an-array'}]}};
assert.doesNotThrow(()=>app._researchClaimsHTML([claim]));
process.stdout.write('Research numeric conflict rendering: 9 checks passed\n');
